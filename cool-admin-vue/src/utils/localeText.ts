function replacePhrases(text: string) {
	return Object.entries(phraseTw).reduce((result, [from, to]) => result.split(from).join(to), text);
}

function replaceChars(text: string) {
	return Array.from(text)
		.map(char => charTw[char] || char)
		.join('');
}

export function localeText(value: any) {
	const text = String(value ?? '');
	return text ? replaceChars(replacePhrases(text)) : text;
}

const textIgnoreTags = new Set(['SCRIPT', 'STYLE', 'NOSCRIPT', 'CODE', 'PRE', 'TEXTAREA']);
const attrNames = ['placeholder', 'title', 'aria-label', 'alt'];

function convertTextNode(node: Text) {
	const value = node.nodeValue || '';
	const next = localeText(value);

	if (next !== value) {
		node.nodeValue = next;
	}
}

function convertElementAttrs(el: Element) {
	attrNames.forEach(name => {
		const value = el.getAttribute(name);

		if (value) {
			const next = localeText(value);

			if (next !== value) {
				el.setAttribute(name, next);
			}
		}
	});
}

function convertNode(node: Node) {
	if (node.nodeType === Node.TEXT_NODE) {
		convertTextNode(node as Text);
		return;
	}

	if (node.nodeType !== Node.ELEMENT_NODE) {
		return;
	}

	const el = node as Element;

	if (textIgnoreTags.has(el.tagName)) {
		return;
	}

	convertElementAttrs(el);

	const walker = document.createTreeWalker(el, NodeFilter.SHOW_TEXT | NodeFilter.SHOW_ELEMENT, {
		acceptNode(child) {
			if (
				child.nodeType === Node.ELEMENT_NODE &&
				textIgnoreTags.has((child as Element).tagName)
			) {
				return NodeFilter.FILTER_REJECT;
			}

			return NodeFilter.FILTER_ACCEPT;
		}
	});

	let current = walker.nextNode();

	while (current) {
		if (current.nodeType === Node.TEXT_NODE) {
			convertTextNode(current as Text);
		} else if (current.nodeType === Node.ELEMENT_NODE) {
			convertElementAttrs(current as Element);
		}

		current = walker.nextNode();
	}
}

export function startTraditionalTextObserver() {
	if (typeof window === 'undefined' || !document.body) {
		return;
	}

	document.documentElement.lang = 'zh-Hant-TW';
	convertNode(document.body);

	const observer = new MutationObserver(records => {
		records.forEach(record => {
			if (record.type === 'characterData') {
				convertNode(record.target);
				return;
			}

			if (record.type === 'attributes') {
				convertElementAttrs(record.target as Element);
				return;
			}

			record.addedNodes.forEach(convertNode);
		});
	});

	observer.observe(document.body, {
		childList: true,
		subtree: true,
		characterData: true,
		attributes: true,
		attributeFilter: attrNames
	});

	return observer;
}
